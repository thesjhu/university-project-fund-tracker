-- University Project Activity Tracker (UPAT)
-- Step 2 of 3: link the tables with foreign keys
-- Dialect: Microsoft Access SQL. Access runs one statement per query,
-- so run each statement on its own (or use the buttons on the automation form).

ALTER TABLE DEPARTMENT
    ADD CONSTRAINT FK_DEPARTMENT_ZIPCODE
    FOREIGN KEY (ZipCode) REFERENCES ZIPCODE (ZipCode)
    ON DELETE NO ACTION ON UPDATE CASCADE;

ALTER TABLE FACULTY
    ADD CONSTRAINT FK_FACULTY_DEPARTMENT
    FOREIGN KEY (DepartmentID) REFERENCES DEPARTMENT (DepartmentID)
    ON DELETE NO ACTION ON UPDATE CASCADE;

ALTER TABLE FUNDSPONSOR
    ADD CONSTRAINT FK_FUNDSPONSOR_SPONSOR
    FOREIGN KEY (SponsorID) REFERENCES SPONSOR (SponsorID)
    ON DELETE NO ACTION ON UPDATE CASCADE;

ALTER TABLE FUNDSPONSOR
    ADD CONSTRAINT FK_FUNDSPONSOR_FUND
    FOREIGN KEY (FundCode) REFERENCES FUND (FundCode)
    ON DELETE NO ACTION ON UPDATE CASCADE;

ALTER TABLE FUND
    ADD CONSTRAINT FK_FUND_PROJECT
    FOREIGN KEY (ProjectID) REFERENCES PROJECT (ProjectID)
    ON DELETE NO ACTION ON UPDATE CASCADE;

ALTER TABLE ACTIVITY
    ADD CONSTRAINT FK_ACTIVITY_PROJECT
    FOREIGN KEY (ProjectID) REFERENCES PROJECT (ProjectID)
    ON DELETE NO ACTION ON UPDATE CASCADE;

ALTER TABLE ACTIVITY
    ADD CONSTRAINT FK_ACTIVITY_DEPARTMENT
    FOREIGN KEY (DepartmentID) REFERENCES DEPARTMENT (DepartmentID)
    ON DELETE NO ACTION ON UPDATE CASCADE;
